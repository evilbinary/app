#define NPATCH 32
#define GRID 10

static GLuint prog, vbo, vao_count;
static GLint loc_mvp, loc_model, loc_pos, loc_nrm;

static void bernstein(float t, float b[4]) {
  float mt = 1.0f - t;
  b[0] = mt * mt * mt;
  b[1] = 3.0f * t * mt * mt;
  b[2] = 3.0f * t * t * mt;
  b[3] = t * t * t;
}
static void bernstein_d(float t, float d[4]) {
  float mt = 1.0f - t;
  d[0] = -3.0f * mt * mt;
  d[1] = 3.0f * mt * mt - 6.0f * t * mt;
  d[2] = 6.0f * t * mt - 3.0f * t * t;
  d[3] = 3.0f * t * t;
}
static void eval_patch(const int *pidx, float u, float v, float pos[3],
                       float nrm[3]) {
  float bu[4], bv[4], du[4], dv[4];
  float px = 0, py = 0, pz = 0;
  float tux = 0, tuy = 0, tuz = 0, tvx = 0, tvy = 0, tvz = 0;
  int i, j;
  bernstein(u, bu);
  bernstein(v, bv);
  bernstein_d(u, du);
  bernstein_d(v, dv);
  for (i = 0; i < 4; i++) {
    for (j = 0; j < 4; j++) {
      const float *cp = cpdata[pidx[i * 4 + j] - 1];
      float w = bu[i] * bv[j], wu = du[i] * bv[j], wv = bu[i] * dv[j];
      px += w * cp[0]; py += w * cp[1]; pz += w * cp[2];
      tux += wu * cp[0]; tuy += wu * cp[1]; tuz += wu * cp[2];
      tvx += wv * cp[0]; tvy += wv * cp[1]; tvz += wv * cp[2];
    }
  }
  pos[0] = px; pos[1] = py; pos[2] = pz;
  {
    float nx = tuy * tvz - tuz * tvy;
    float ny = tuz * tvx - tux * tvz;
    float nz = tux * tvy - tuy * tvx;
    float len = sqrtf(nx * nx + ny * ny + nz * nz);
    if (len > 1e-8f) { nx /= len; ny /= len; nz /= len; }
    else { nx = 0; ny = 0; nz = 1; }
    nrm[0] = nx; nrm[1] = ny; nrm[2] = nz;
  }
}

static int build_mesh(void) {
  int per_patch = GRID * GRID * 2 * 3;
  int total = NPATCH * per_patch;
  float *v = malloc((size_t)total * 6 * sizeof(float));
  float lat_pos[GRID + 1][GRID + 1][3];
  float lat_nrm[GRID + 1][GRID + 1][3];
  int p, a, b;
  static int nv;
  nv = 0;
  if (!v) return -1;
  for (p = 0; p < NPATCH; p++) {
    const int *pidx = patches[p];
    for (a = 0; a <= GRID; a++)
      for (b = 0; b <= GRID; b++)
        eval_patch(pidx, (float)a / GRID, (float)b / GRID,
                   lat_pos[a][b], lat_nrm[a][b]);
    for (a = 0; a < GRID; a++) {
      for (b = 0; b < GRID; b++) {
        int corners[4][2] = {{a, b}, {a + 1, b}, {a + 1, b + 1}, {a, b + 1}};
        static const int tri[6] = {0, 1, 2, 0, 2, 3};
        int k;
        for (k = 0; k < 6; k++) {
          int pp = tri[k];
          int aa = corners[pp][0], bb = corners[pp][1];
          float *dst = v + (size_t)nv * 6;
          dst[0] = lat_pos[aa][bb][0];
          dst[1] = lat_pos[aa][bb][1];
          dst[2] = lat_pos[aa][bb][2];
          dst[3] = lat_nrm[aa][bb][0];
          dst[4] = lat_nrm[aa][bb][1];
          dst[5] = lat_nrm[aa][bb][2];
          nv++;
        }
      }
    }
  }
  glGenBuffers(1, &vbo);
  glBindBuffer(GL_ARRAY_BUFFER, vbo);
  glBufferData(GL_ARRAY_BUFFER, (GLsizeiptr)nv * 6 * sizeof(float), v,
               GL_STATIC_DRAW);
  free(v);
  vao_count = nv;
  return 0;
}

static int init(void) {
  static const char *vs =
      "attribute vec4 aPosition;\n"
      "attribute vec3 aNormal;\n"
      "uniform mat4 uMVP;\n"
      "uniform mat4 uModel;\n"
      "varying vec3 vN;\n"
      "void main() {\n"
      "  vec4 p = uModel * aPosition;\n"
      "  vN = mat3(uModel) * aNormal;\n"
      "  gl_Position = uMVP * p;\n"
      "}\n";
  static const char *fs =
      "precision mediump float;\n"
      "varying vec3 vN;\n"
      "void main() {\n"
      "  vec3 N = normalize(vN);\n"
      "  vec3 L = normalize(vec3(0.5, 0.7, -0.6));\n"
      "  vec3 V = vec3(0.0, 0.0, 1.0);\n"
      "  float d = max(dot(N, L), 0.0);\n"
      "  vec3 base = vec3(0.86, 0.44, 0.22);\n"
      "  vec3 c = base * (0.22 + 0.78 * d);\n"
      "  c += vec3(0.5) * pow(max(dot(reflect(-L, N), V), 0.0), 24.0);\n"
      "  gl_FragColor = vec4(c, 1.0);\n"
      "}\n";
  prog = demo_program(vs, fs);
  if (!prog) return -1;
  loc_mvp = glGetUniformLocation(prog, "uMVP");
  loc_model = glGetUniformLocation(prog, "uModel");
  loc_pos = glGetAttribLocation(prog, "aPosition");
  loc_nrm = glGetAttribLocation(prog, "aNormal");
  if (build_mesh() != 0) return -1;
  glEnable(GL_CULL_FACE);
  glCullFace(GL_BACK);
  return 0;
}

static void draw(float t) {
  mat4 proj, view, model, pv;
  if (!prog) return;
  mat4_perspective(&proj, 42.0f, 640.0f / 480.0f, 0.5f, 100.0f);
  mat4_identity(&view);
  mat4_translate(&view, 0.0f, 0.0f, -8.0f);
  mat4_mul(&pv, &proj, &view);
  mat4_identity(&model);
  mat4_translate(&model, 0.0f, 0.0f, -1.5f);
  mat4_rotate(&model, t * 40.0f, 0.0f, 0.0f, 1.0f);
  mat4_rotate(&model, 90.0f, 1.0f, 0.0f, 0.0f);
  glUseProgram(prog);
  glUniformMatrix4fv(loc_mvp, 1, GL_FALSE, pv.m);
  glUniformMatrix4fv(loc_model, 1, GL_FALSE, model.m);
  glBindBuffer(GL_ARRAY_BUFFER, vbo);
  glEnableVertexAttribArray(loc_pos);
  glEnableVertexAttribArray(loc_nrm);
  glVertexAttribPointer(loc_pos, 3, GL_FLOAT, GL_FALSE, 6 * sizeof(float),
                        (void *)0);
  glVertexAttribPointer(loc_nrm, 3, GL_FLOAT, GL_FALSE, 6 * sizeof(float),
                        (void *)(3 * sizeof(float)));
  glDrawArrays(GL_TRIANGLES, 0, vao_count);
}

int main(void) { demo_set_title("Teapot"); return demo_run(init, draw); }
